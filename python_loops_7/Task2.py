# Список транзакций, полученных от платежного шлюза
raw_transactions = ["SUCCESS:100", "FAILED:50", "SUCCESS:-10", "SUCCESS:0", "SUCCESS:250", "ERROR:200"]

# Генератор списка для очистки транзакций:
# 1. Проходим по каждому элементу t в списке raw_transactions.
# 2. Проверяем, что строка начинается с "SUCCESS:" (первые 8 символов).
# 3. Извлекаем число после двоеточия с помощью split(":")[1] и превращаем его в int.
# 4. Проверяем, что сумма больше 0 (отсеиваем отрицательные и нулевые транзакции).
# 5. Добавляем только те суммы, которые прошли все условия.
clean_transactions = [int(t.split(":")[1]) for t in raw_transactions if t[:8] == "SUCCESS:" and int(t.split(":")[1]) > 0]

# Выводим результат
print("Очищенные транзакции:", clean_transactions)